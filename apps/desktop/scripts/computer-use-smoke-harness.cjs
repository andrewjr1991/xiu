const { app, BrowserWindow, dialog, protocol } = require("electron");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const os = require("node:os");
app.setPath("userData", require("node:fs").mkdtempSync(path.join(os.tmpdir(), "xiu-computer-smoke-user-")));
protocol.registerSchemesAsPrivileged([{ scheme: "xiu-preview", privileges: { standard: true, secure: true, supportFetchAPI: true } }]);
app.disableHardwareAcceleration();
app.whenReady().then(async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "xiu-computer-fixture-"));
  const owner = new BrowserWindow({ show: false });
  const { ComputerUseController } = require(process.argv[2]);
  const controller = new ComputerUseController(owner);
  try {
    await fs.mkdir(path.join(root, "site"));
    await fs.writeFile(path.join(root, "site", "index.html"), '<!doctype html><title>Local fixture</title><script src="core.js"></script><h1>Observed fixture</h1>');
    await fs.writeFile(path.join(root, "site", "core.js"), 'window.fixtureLoaded = 42;');
    await fs.writeFile(path.join(root, "outside.js"), 'window.outsideCanary = true;');
    let pickCalls = 0;
    dialog.showOpenDialog = async () => { pickCalls++; return { canceled: false, filePaths: [path.join(root, "site", "index.html")] }; };
    dialog.showMessageBox = async (_owner, options) => { assert.equal(options.defaultId, 0); assert.equal(options.cancelId, 0); return { response: 1 }; };
    await assert.rejects(controller.control(root, { action: "open" }, true), /Plan/);
    assert.equal(pickCalls, 0);
    assert.equal((await controller.control(root, { action: "open" }, false)).state, "observing");
    const target = BrowserWindow.getAllWindows().find(window => window !== owner);
    assert(target);
    const prefs = target.webContents.getLastWebPreferences();
    assert.equal(prefs.sandbox, true); assert.equal(prefs.nodeIntegration, false); assert.equal(prefs.preload, undefined);
    assert.deepEqual(await target.webContents.executeJavaScript('({fixture:window.fixtureLoaded, node:typeof require, process:typeof process, bridge:typeof window.xiuDesktop})'), { fixture: 42, node: "undefined", process: "undefined", bridge: "undefined" });
    assert.equal(await target.webContents.executeJavaScript('fetch("https://example.com").then(()=>true,()=>false)'), false);
    assert.equal(await target.webContents.executeJavaScript('fetch("file:///C:/Windows/win.ini").then(()=>true,()=>false)'), false);
    assert.equal(await target.webContents.executeJavaScript('window.open("https://example.com")===null'), true);
    const isolated = target.webContents.session;
    assert.equal((await isolated.fetch("xiu-preview://local/outside.js")).status, 403);
    assert.equal((await isolated.fetch("xiu-preview://local/site/.env")).status, 403);
    assert.equal((await isolated.fetch("xiu-preview://local/site/core.js", { method: "POST" }).catch(() => ({ status: 403 }))).status, 403);
    assert.match((await controller.control(root, { action: "capture" }, false)).screenshot, /^data:image\/png;base64,/);
    controller.stop(); assert.equal(target.isDestroyed(), true);
    assert.equal((await controller.control(root, { action: "state" }, false)).screenshot, undefined);
    await assert.rejects(controller.control(root, { action: "capture" }, false));
    dialog.showMessageBox = async () => ({ response: 0 });
    assert.equal((await controller.control(root, { action: "open" }, false)).state, "idle");
    let confirm;
    dialog.showMessageBox = () => new Promise(resolve => { confirm = resolve; });
    const late = controller.control(root, { action: "open" }, false);
    while (!confirm) await new Promise(resolve => setTimeout(resolve, 10));
    controller.stop(); confirm({ response: 1 });
    assert.equal((await late).state, "idle");
    assert.equal(BrowserWindow.getAllWindows().length, 1);
    console.log("Computer preview smoke passed: independent consent/cancel, Plan refusal, sandbox local JS, network/file/POST/popup denial, target-only capture, stop and late-consent cancellation.");
    controller.stop(); owner.destroy(); app.exit(0);
  } catch (error) { console.error(error); controller.stop(); owner.destroy(); app.exit(1); }
}).catch(error => { console.error(error); app.exit(1); });
